import test from 'node:test';
import assert from 'node:assert/strict';
import {randomBytes} from 'node:crypto';
import {DatabaseSync} from 'node:sqlite';
import {HostingStore} from '../src/store.mjs';
import {HostedRoles} from '../src/hosting.mjs';
import {HostedProfiles} from '../src/profiles.mjs';
import {HostedConversations} from '../src/conversations.mjs';
import {hostingServer} from '../src/http.mjs';
import {portalHostingAuthority} from '../src/portal-authority.mjs';
import {hostedPortalClient} from '../src/portal-client.mjs';
import {PROTOCOL} from '../src/protocol.mjs';

test('website authority and real HTTP transport keep owner keys private and viewer dialogue separate',async t=>{
  const store=new HostingStore(':memory:'),website=new DatabaseSync(':memory:');
  const grantKey=randomBytes(32),serviceKey=randomBytes(32),roleUuid='00000000-0000-0000-0000-000000000001',creator='00000000-0000-0000-0000-000000000002';
  website.exec('CREATE TABLE ownerships(agent_uuid TEXT PRIMARY KEY,owner_id TEXT); CREATE TABLE numen_creator_relations(player_uuid TEXT PRIMARY KEY,name TEXT,creator_uuid TEXT,state TEXT,last_seen INTEGER);');
  const insert=website.prepare('INSERT INTO ownerships VALUES(?,?)');insert.run(roleUuid,'owner');insert.run(creator,'owner');
  website.prepare('INSERT INTO numen_creator_relations VALUES(?,?,?,?,?)').run(roleUuid,'HostedTest',creator,'bound',Date.now());
  let bindings=0,stops=0,delivered=0,speaker;
  const profile={revision:0,harness:'native',provider:'test',model:'synthetic',goal:'探索公会',apiKey:'synthetic-private-key'};
  const profiles=new HostedProfiles({store,key:randomBytes(32),catalogue:{providers:[{id:'test',label:'Test',models:[{id:'synthetic',label:'Synthetic',privateEndpoint:'not-public'}]}],harnesses:[{id:'native',label:'Native',mode:'numen',providers:['test']}]},adapters:{native:{isolatedByok:true,async bind({role,profile:p,apiKey}){
    assert.equal(role.ownerId,'owner');assert.equal(apiKey,profile.apiKey);assert.equal(p.model,'synthetic');bindings++;
    return{isolatedByok:true,model:p.model,ownerId:role.ownerId,async close(){stops++;return{stopped:true};}};
  }}}});
  const result=(role,lease)=>({protocol:PROTOCOL,bodyKind:'numen',roleUuid:role.roleUuid,serverId:role.serverId,name:role.name,fenced:true,ready:true,mode:lease.mode??'paused',epoch:lease.epoch});
  const body={attach:async(r,l)=>result(r,l),transition:async(r,l)=>result(r,l),prepare:async()=>{},async message(role,value){delivered++;speaker=value.speaker;return{id:value.id,state:'completed',delivered:true};}};
  const hosting=new HostedRoles({store,body,profiles}),conversations=new HostedConversations({store,hosting,body});
  const transport=hostingServer({hosting,conversations,grantKey,serviceKey}),address=await transport.listen();
  t.after(async()=>{transport.server.closeAllConnections();await new Promise(r=>transport.server.close(r));website.close();store.close();});
  const authority=portalHostingAuthority({store:{db:website},serverId:'isolated',grantKey});
  const client=hostedPortalClient({authority,endpoint:`http://127.0.0.1:${address.port}/v1/hosting`,serviceKey});
  const owner={id:'owner',username:'Owner'},viewer={id:'viewer',username:'Viewer'};
  const call=(op,data={},who=owner,conversation=false)=>client.request({owner:who,roleUuid,op,data,conversation});
  const saved=await call('configure',{profile});assert.equal(saved.keyConfigured,true);
  const exposed=JSON.stringify(await call('profile'));assert.ok(!exposed.includes(profile.apiKey));assert.ok(!exposed.includes('not-public'));
  await assert.rejects(call('profile',{},viewer),{code:'ROLE_NOT_OWNED'});
  await assert.rejects(call('profile',{},viewer,true),{code:'SCOPE_DENIED'});
  assert.equal(bindings,0);await call('attach');await call('mode',{mode:'numen'});assert.equal(bindings,1);
  const message={id:'same-request-001',text:'公会在哪里？'};
  assert.equal((await call('message',message,viewer,true)).state,'delivered');
  assert.equal((await call('message',message,viewer,true)).state,'delivered');assert.equal(delivered,1);assert.equal(speaker,'Viewer');
  assert.equal((await call('messages',{},owner,true)).messages.length,0);
  assert.equal((await call('messages',{},viewer,true)).messages.length,1);
  await assert.rejects(call('configure',{profile:{...profile,revision:1}}),{code:'HOSTING_MUST_PAUSE'});
  await call('pause');assert.equal(stops,1);
  await assert.rejects(call('message',{id:'paused-request-002',text:'出发吧'},viewer,true),{code:'AGENT_NOT_LISTENING'});
  hosting.status=()=>{throw Object.assign(Error('synthetic-private-key internal database details'),{code:'SQLITE_INTERNAL'});};
  await assert.rejects(call('status'),e=>e.code==='BACKEND_UNAVAILABLE'&&!String(e).includes(profile.apiKey));
});
